import { GAME_TYPES, BONUS_MECHANICS } from '../../mechanics/registry.js';
import { PaytableValidator } from '../math/PaytableValidator.js';

export class GDDGenerator {
  constructor(project) {
    this.project = project;
  }

  generate() {
    const p = this.project;
    const m = p.math;
    const gt = GAME_TYPES[m.gameType] || {};
    const validator = new PaytableValidator(p);
    const issues = validator.validate();

    return `
================================================================================
  GAME DESIGN DOCUMENT — ${p.name}
  Generated by StakeStudio | ${new Date().toISOString().split('T')[0]}
  Version: ${p.version}
================================================================================

1. OVERVIEW
────────────────────────────────────────
  Game Name:     ${p.name}
  Game Type:     ${gt.name || m.gameType}
  Description:   ${gt.description || '—'}
  Theme/Style:   ${p.theme.style || 'Not specified'}
  Lore:          ${p.theme.lore || 'Not specified'}
  Game ID:       ${p.build.stakeEngine.gameId || '—'}
  Provider:      ${p.build.stakeEngine.providerName || '—'}

2. GRID & LAYOUT
────────────────────────────────────────
  Reels:         ${m.grid.reels}
  Rows:          ${m.grid.rows.join(', ')}
  Total Cells:   ${m.grid.rows.reduce((a, b) => a + b, 0)}
${m.gameType === 'ways' || m.gameType === 'waysLarge' || m.gameType === 'megaways'
  ? `  Ways:          ${m.grid.rows.reduce((a, b) => a * b, 1).toLocaleString()}`
  : ''}

3. MATH MODEL
────────────────────────────────────────
  Target RTP:    ${(m.rtp * 100).toFixed(2)}%
  Win Cap:       ${m.wincap.toLocaleString()}x
  Volatility:    ${m.volatility}
  Hit Frequency: Determined by simulation

4. SYMBOLS
────────────────────────────────────────
${this.formatSymbolTable()}

5. SPECIAL SYMBOLS
────────────────────────────────────────
  Wild:          ${(m.specialSymbols?.wild || []).join(', ') || 'None'}
  Scatter:       ${(m.specialSymbols?.scatter || []).join(', ') || 'None'}
  Other:         ${Object.entries(m.specialSymbols || {})
    .filter(([k]) => k !== 'wild' && k !== 'scatter')
    .map(([k, v]) => `${k}: ${Array.isArray(v) ? v.join(', ') : v}`)
    .join('; ') || 'None'}

6. PAYTABLE
────────────────────────────────────────
${this.formatPaytable()}

7. BONUS MECHANICS
────────────────────────────────────────
${m.bonusMechanics.length > 0
  ? m.bonusMechanics.map(key => {
      const mech = BONUS_MECHANICS[key];
      return `  • ${mech?.name || key}\n    ${mech?.description || ''}`;
    }).join('\n')
  : '  None configured'}

8. FREE SPINS
────────────────────────────────────────
${this.formatFreespinTriggers()}

9. BET MODES
────────────────────────────────────────
${this.formatBetModes()}

10. REEL STRIPS
────────────────────────────────────────
${this.formatReelStrips()}

11. ANIMATION STATES
────────────────────────────────────────
${this.formatAnimationStates()}

12. AUDIO MAPPING
────────────────────────────────────────
${this.formatAudio()}

13. BUILD CONFIG
────────────────────────────────────────
  Game ID:         ${p.build.stakeEngine.gameId || '—'}
  Provider Name:   ${p.build.stakeEngine.providerName || '—'}
  Provider Number: ${p.build.stakeEngine.providerNumber || '—'}
  Team Name:       ${p.build.stakeEngine.teamName || '—'}
  Sim Rounds Base: ${p.build.simulations.base.toLocaleString()}
  Sim Rounds Bonus:${p.build.simulations.bonus.toLocaleString()}

14. VALIDATION REPORT
────────────────────────────────────────
  Total Issues: ${issues.length}
${issues.length > 0
  ? issues.map(i => `  [${i.severity.toUpperCase()}] ${i.category}: ${i.message}`).join('\n')
  : '  All checks passed.'}

================================================================================
  END OF DOCUMENT
================================================================================
`.trim();
  }

  formatSymbolTable() {
    const syms = this.project.theme.symbols || [];
    if (syms.length === 0) return '  No symbols defined.';

    const lines = ['  Name       Tier       3x     4x     5x'];
    lines.push('  ' + '─'.repeat(46));
    for (const s of syms) {
      const p = s.payouts || {};
      lines.push(`  ${(s.name || '').padEnd(10)} ${(s.tier || '').padEnd(10)} ${String(p[3] || '—').padEnd(6)} ${String(p[4] || '—').padEnd(6)} ${String(p[5] || '—')}`);
    }
    return lines.join('\n');
  }

  formatPaytable() {
    const syms = (this.project.theme.symbols || []).filter(s => s.tier !== 'special');
    if (syms.length === 0) return '  No paytable data.';

    const lines = [];
    for (const s of syms) {
      const p = s.payouts || {};
      const pays = [3, 4, 5].map(n => p[n] ? `${n}x: ${p[n]}` : null).filter(Boolean).join('  ');
      lines.push(`  ${s.name}: ${pays || 'No payouts'}`);
    }
    return lines.join('\n');
  }

  formatFreespinTriggers() {
    const triggers = this.project.math.freespinTriggers || {};
    if (Object.keys(triggers).length === 0) return '  No free spin triggers.';

    const lines = [];
    for (const [mode, t] of Object.entries(triggers)) {
      lines.push(`  ${mode}:`);
      for (const [count, spins] of Object.entries(t)) {
        lines.push(`    ${count} scatters → ${spins} free spins`);
      }
    }
    return lines.join('\n');
  }

  formatBetModes() {
    const modes = this.project.math.betModes || [];
    if (modes.length === 0) return '  No bet modes.';

    return modes.map(m =>
      `  • ${m.name}\n    Cost: ${m.cost}x | RTP: ${(m.rtp * 100).toFixed(1)}% | Max Win: ${m.maxWin}x` +
      `${m.isBuyBonus ? ' | Buy Bonus' : ''}${m.isFeature ? ' | Feature' : ''}`
    ).join('\n');
  }

  formatReelStrips() {
    const strips = this.project.math.reelStrips;
    if (!strips || Object.keys(strips).length === 0) return '  No reel strips defined (using weighted random).';

    const lines = [];
    for (const [key, reels] of Object.entries(strips)) {
      const label = key === 'BR' ? 'Base Game' : key === 'FR' ? 'Free Spins' : key;
      lines.push(`  ${label}:`);
      for (let i = 0; i < reels.length; i++) {
        const counts = {};
        for (const s of reels[i]) counts[s] = (counts[s] || 0) + 1;
        const summary = Object.entries(counts).map(([s, c]) => `${s}:${c}`).join(' ');
        lines.push(`    Reel ${i + 1} (${reels[i].length} stops): ${summary}`);
      }
    }
    return lines.join('\n');
  }

  formatAnimationStates() {
    const states = this.project.animation.states;
    return Object.entries(states)
      .map(([name, s]) => `  ${name}: ${s.duration ? s.duration + 'ms' : 'indefinite'} (${s.layers.length} layers)`)
      .join('\n');
  }

  formatAudio() {
    const audio = this.project.audio;
    const lines = [];
    const director = audio.director || {};
    const buses = director.buses || {};
    lines.push(`  Audio Director: ${director.enabled === false ? 'disabled' : 'enabled'}`);
    lines.push(`    Buses: ${Object.entries(buses).map(([key, value]) => `${key}=${value}`).join(' ') || 'defaults'}`);
    lines.push(`    Ducking: ${director.ducking?.enabled === false ? 'off' : 'on'} (${Math.round(Number(director.ducking?.amount || 0) * 100)}%, ${director.ducking?.attackMs || 0}ms/${director.ducking?.releaseMs || 0}ms)`);
    lines.push('  Music Layers:');
    for (const [key, val] of Object.entries(audio.layers)) {
      lines.push(`    ${key}: ${val?.src || 'Not assigned'}`);
    }
    lines.push('  Stingers:');
    for (const [key, val] of Object.entries(audio.stingers)) {
      const assigned = val ? (Array.isArray(val) ? `${val.filter(Boolean).length} assigned` : (val.src || 'configured')) : 'Not assigned';
      lines.push(`    ${key}: ${assigned}`);
    }
    return lines.join('\n');
  }

  downloadAsText() {
    const text = this.generate();
    const blob = new Blob([text], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${this.project.name.replace(/\s+/g, '_')}_GDD.txt`;
    a.click();
    URL.revokeObjectURL(url);
  }
}
